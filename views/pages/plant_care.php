                    <li><strong>Low to Medium Indirect:</strong> Sansevieria Snake Plant, ZZ Plant, Aglaonema (tolerates corners and office fluorescent bulbs).</li>
                    <li><strong>Bright Filtered Light:</strong> Peace Lily, Monstera Deliciosa, Fiddle Leaf Fig, Areca Palm (placed 2-3 feet from an east or north window).</li>
                    <li><strong>Full Direct Sun:</strong> Mogra Jasmine, Desi Rose, Bougainvillea, Fruit saplings (require 4-6 hours open balcony sunshine).</li>

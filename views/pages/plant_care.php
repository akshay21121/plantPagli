                    <li>Check soil moisture by dipping your index finger 1 inch into the potting mix. Water gently if dry.</li>
                    <li>Do <strong>not</strong> repot immediately. Allow the plant 7-10 days to adapt to your room's temperature and humidity.</li>
                </ul>

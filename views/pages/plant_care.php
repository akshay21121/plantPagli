                <p style="font-size: 14.5px; line-height: 1.6;">
                    More houseplants in India perish from overwatering than underwatering! Always check the top 1-2 inches of soil before adding water. If the soil clings to your fingers, wait another day. Ensure your pot has clear drainage holes so excess water escapes freely into the saucer.
                </p>
